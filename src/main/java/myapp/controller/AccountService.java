package myapp.controller;

import myapp.entity.AccountRow;
import myapp.entity.AccountStore;
import myapp.entity.AccountTallyRow;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;

import java.time.LocalDateTime;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

// CONTROL layer for requirement 1: "support and manage different types of user accounts
// and user profiles". All business rules live here, never in the Controller and never in
// the HTML — that is the b-c-e rule "control classes contain the application-specific
// business rules" (复习笔记/04. Advanced UML II.md:479).
//
// Every rule below mirrors a real constraint in usersDB.sql / designer_profileDB.sql.
// The DB is the backstop; this class exists to turn a raw "Data truncated" or CHECK
// violation into a friendly, field-by-field error the page can show.
@Service
public class AccountService {

    private static final Pattern EMAIL = Pattern.compile("^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$");

    // These two lists are a Java-side copy of the CHECK constraints in usersDB.sql:18-19.
    // Duplicating them is intentional: the DB guarantees no bad value can EVER be stored,
    // the Service guarantees the user sees a readable message instead of a 500.
    private static final List<String> ROLE_ORDER = List.of(
            "USER_ADMIN", "INTERIOR_DESIGNER", "CUSTOMER", "PLATFORM_MANAGEMENT");
    private static final Set<String> ROLES = Set.copyOf(ROLE_ORDER);
    private static final Set<String> STATUSES = Set.of("ACTIVE", "SUSPENDED");

    private static final int MAX_NAME = 100;            // users.name VARCHAR(100)
    private static final int MAX_EMAIL = 255;           // users.email VARCHAR(255)
    private static final int MAX_PHONE = 30;            // users.phone VARCHAR(30)
    private static final int MAX_BIO = 2000;            // designer_profile.bio VARCHAR(2000)
    private static final int MAX_SPECIALISATION = 150;  // designer_profile.specialisation VARCHAR(150)

    private final AccountStore store;

    public AccountService(AccountStore store) {
        this.store = store;
    }

    // ---------------------------------------------------------------- reads

    @Transactional(readOnly = true)
    public List<AccountListItem> list(String role, String status, String q, boolean includeDeleted) {
        validateFilters(role, status);
        return store.list(role, status, q, includeDeleted).stream()
                .map(AccountService::toListItem)
                .toList();
    }

    @Transactional(readOnly = true)
    public AccountResponse get(Integer id) {
        return toResponse(requireAccount(id));
    }

    @Transactional(readOnly = true)
    public AccountSummaryResponse summary() {
        Map<String, Long> byRole = new LinkedHashMap<>();
        for (String r : ROLE_ORDER) byRole.put(r, 0L);  // fixed display order in the JSON

        long total = 0, active = 0, suspended = 0, deleted = 0;
        for (AccountTallyRow t : store.tallies()) {
            total += t.count();
            byRole.merge(t.role(), t.count(), Long::sum);
            if (t.deleted()) deleted += t.count();
            else if ("SUSPENDED".equals(t.status())) suspended += t.count();
            else active += t.count();
        }
        return new AccountSummaryResponse(total, active, suspended, deleted, byRole);
    }

    // ---------------------------------------------------------------- writes

    @Transactional
    public AccountResponse create(AccountUpsertRequest request) {
        Fields f = validate(request, null);
        // A new account always starts ACTIVE. "Suspend" is a separate use case with its own
        // endpoint, so a create form cannot accidentally create a disabled account.
        Integer id = store.insert(f.name(), f.email(), f.phone(), f.role(), "ACTIVE");
        // Re-read: created_at / updated_at are generated by MySQL, not by Java. Without
        // this the response would contain null timestamps (same lesson as
        // ProjectManagementService.java:75-76).
        return toResponse(requireAccount(id));
    }

    @Transactional
    public AccountResponse update(Integer id, AccountUpsertRequest request) {
        requireEditable(id);
        Fields f = validate(request, id);   // exclude this row from the duplicate-email check
        store.update(id, f.name(), f.email(), f.phone(), f.role());
        return toResponse(requireAccount(id));
    }

    @Transactional
    public AccountResponse changeStatus(Integer id, AccountStatusRequest request) {
        requireEditable(id);
        Map<String, String> errors = new HashMap<>();
        String status = trim(request.status()).toUpperCase(Locale.ROOT);
        if (!STATUSES.contains(status)) {
            errors.put("status", "Status must be ACTIVE or SUSPENDED");
        }
        if (!errors.isEmpty()) throw new ValidationException(errors);
        store.setStatus(id, status);
        return toResponse(requireAccount(id));
    }

    // Soft delete only. A physical DELETE would violate the foreign keys from company,
    // designer_profile, interior_design_project, favourite and idp_view.
    @Transactional
    public void delete(Integer id) {
        requireEditable(id);
        store.setDeleted(id, true);
    }

    // A separate endpoint because "suspend" (reversible state) and "soft delete"
    // (disappears from lists but keeps the email reserved) are different use cases with
    // different UI buttons. Merging them would leave no way to implement "restore".
    @Transactional
    public AccountResponse restore(Integer id) {
        AccountRow row = requireAccount(id);
        if (!row.deleted()) {
            throw new ValidationException(Map.of("deleted", "This account is not deleted"));
        }
        store.setDeleted(id, false);
        return toResponse(requireAccount(id));
    }

    @Transactional
    public AccountResponse updateProfile(Integer id, AccountProfileRequest request) {
        AccountRow row = requireEditable(id);
        Map<String, String> errors = new HashMap<>();

        // Only designers have a role-specific profile table in the current schema.
        // This is the honest boundary of "user profiles" here: shared fields are handled
        // by update(), and designer extras by this method.
        if (!"INTERIOR_DESIGNER".equals(row.role())) {
            errors.put("role", "Only interior designers have a designer profile to edit");
        }

        String bio = trim(request.bio());
        if (bio.length() > MAX_BIO) {
            errors.put("bio", "Bio must be " + MAX_BIO + " characters or fewer");
        }
        String specialisation = trim(request.specialisation());
        if (specialisation.length() > MAX_SPECIALISATION) {
            errors.put("specialisation", "Specialisation must be " + MAX_SPECIALISATION + " characters or fewer");
        }

        Integer years = null;
        String yearsText = trim(request.yearsExperience());
        if (!yearsText.isEmpty()) {
            try {
                years = Integer.valueOf(yearsText);
                // Mirrors chk_profile_years in designer_profileDB.sql:11
                if (years < 0 || years > 80) {
                    errors.put("yearsExperience", "Years of experience must be between 0 and 80");
                }
            } catch (NumberFormatException e) {
                errors.put("yearsExperience", "Years of experience must be a whole number");
            }
        }

        if (!errors.isEmpty()) throw new ValidationException(errors);

        store.upsertDesignerProfile(id,
                bio.isEmpty() ? null : bio,
                years,
                specialisation.isEmpty() ? null : specialisation);
        return toResponse(requireAccount(id));
    }

    // ---------------------------------------------------------------- rules / helpers

    private void validateFilters(String role, String status) {
        Map<String, String> errors = new HashMap<>();
        if (role != null && !role.isBlank() && !ROLES.contains(role)) {
            errors.put("role", "Unknown role filter");
        }
        if (status != null && !status.isBlank() && !STATUSES.contains(status)) {
            errors.put("status", "Unknown status filter");
        }
        if (!errors.isEmpty()) throw new ValidationException(errors);
    }

    // Collect ALL field errors before throwing. GlobalExceptionHandler turns this into
    // HTTP 400 {"errors": {...}} and manage-accounts.html renders them into err-<field>
    // paragraphs, so the user fixes everything in one pass.
    private Fields validate(AccountUpsertRequest request, Integer excludeId) {
        Map<String, String> errors = new HashMap<>();

        String name = trim(request.name());
        if (name.isEmpty()) {
            errors.put("name", "Name is required");
        } else if (name.length() > MAX_NAME) {
            errors.put("name", "Name must be " + MAX_NAME + " characters or fewer");
        }

        // Lower-casing makes uniqueness predictable; MySQL's default utf8mb4 collation is
        // already case-insensitive, so this just makes the Java check agree with the DB.
        String email = trim(request.email()).toLowerCase(Locale.ROOT);
        if (email.isEmpty()) {
            errors.put("email", "Email is required");
        } else if (!EMAIL.matcher(email).matches()) {
            errors.put("email", "Please enter a valid email address, e.g. name@example.com");
        } else if (email.length() > MAX_EMAIL) {
            errors.put("email", "Email must be " + MAX_EMAIL + " characters or fewer");
        } else if (store.emailExists(email, excludeId)) {
            errors.put("email", "This email is already used by an account (including deleted accounts)");
        }

        String phone = trim(request.phone());
        if (phone.length() > MAX_PHONE) {
            errors.put("phone", "Phone number must be " + MAX_PHONE + " characters or fewer");
        }

        String role = trim(request.role()).toUpperCase(Locale.ROOT);
        if (!ROLES.contains(role)) {
            errors.put("role", "Role must be one of: " + String.join(", ", ROLE_ORDER));
        }

        if (!errors.isEmpty()) throw new ValidationException(errors);
        return new Fields(name, email, phone.isEmpty() ? null : phone, role);
    }

    private AccountRow requireAccount(Integer id) {
        return store.findById(id)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND,
                        "No account with id " + id));
    }

    // Deleted accounts are invisible to every write path. Returning 404 for both "not
    // found" and "not editable" leaks no information about which ids exist.
    private AccountRow requireEditable(Integer id) {
        AccountRow row = requireAccount(id);
        if (row.deleted()) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "No account with id " + id);
        }
        return row;
    }

    private static AccountListItem toListItem(AccountRow r) {
        return new AccountListItem(r.id(), r.name(), r.email(), r.phone(), r.role(),
                r.status(), r.deleted(), iso(r.createdAt()));
    }

    private static AccountResponse toResponse(AccountRow r) {
        AccountProfile profile = "INTERIOR_DESIGNER".equals(r.role())
                ? new AccountProfile(r.bio(), r.yearsExperience(), r.specialisation(), r.companyName())
                : null;
        return new AccountResponse(r.id(), r.name(), r.email(), r.phone(), r.role(), r.status(),
                r.deleted(), iso(r.createdAt()), iso(r.updatedAt()), profile);
    }

    private static String iso(LocalDateTime value) {
        return value == null ? null : value.toString();
    }

    private static String trim(String s) {
        return s == null ? "" : s.trim();
    }

    // The validated, ready-to-save values from one create/edit submission. Same idea as
    // the private record Fields(...) at ProjectManagementService.java:212-213.
    private record Fields(String name, String email, String phone, String role) {}
}
